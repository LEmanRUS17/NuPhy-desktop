const I18N = {
  lang: 'ru',
  t(key, vars) {
    const s = STRINGS[this.lang][key] ?? STRINGS.ru[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, v) => vars[v] ?? '') : s;
  },
  effects() { return EFFECT_NAMES[this.lang]; },
  // pick from a {ru, en} pair (or return a plain string as is)
  pick(v) { return v && typeof v === 'object' ? v[this.lang] ?? v.ru : v; },
  init() {
    let saved = null;
    try { saved = localStorage.getItem('lang'); } catch { /* storage unavailable */ }
    this.lang = saved === 'en' || saved === 'ru' ? saved : (navigator.language || 'ru').startsWith('ru') ? 'ru' : 'en';
  },
  set(lang) {
    this.lang = lang;
    try { localStorage.setItem('lang', lang); } catch { /* storage unavailable */ }
  },
  // static markup: data-i18n (text), data-i18n-title, data-i18n-ph (placeholder)
  apply(root = document) {
    document.documentElement.lang = this.lang;
    root.querySelectorAll('[data-i18n]').forEach(e => (e.textContent = this.t(e.dataset.i18n)));
    root.querySelectorAll('[data-i18n-title]').forEach(e => (e.title = this.t(e.dataset.i18nTitle)));
    root.querySelectorAll('[data-i18n-ph]').forEach(e => (e.placeholder = this.t(e.dataset.i18nPh)));
  },
};

I18N.init();
window.I18N = I18N;
window.t = (k, v) => I18N.t(k, v);

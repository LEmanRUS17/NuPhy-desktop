// Regenerates src/boards.js from QMK keyboard.json files in ref/ (nuphy-src/qmk_firmware, branch nuphy-keyboards).
// Usage: node tools/gen-boards.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const C4 = ['mac', 'macfn', 'win', 'winfn', 'extra'];
const C7 = ['mac', 'macfn', 'macfn2', 'win', 'winfn', 'winfn2', 'extra'];

// custom keycodes: order of `enum custom_keycodes` in each board's ansi.h (starting at QK_KB_0)
const BASE = 'RF_DFU LNK_USB LNK_RF LNK_BLE1 LNK_BLE2 LNK_BLE3 MAC_TASK MAC_SEARCH MAC_VOICE MAC_CONSOLE';
const MODELS = [
  { file: 'air75_v2_ansi', match: 'Air75 V2', pids: [0x3245, 0x3246], roles: ['mac', 'macfn', 'win', 'winfn', 'fnm'],
    custom: `${BASE} MAC_PRT MAC_PRTA SIDE_VAI SIDE_VAD SIDE_MOD SIDE_HUI SIDE_SPI SIDE_SPD DEV_RESET SLEEP_MODE BAT_SHOW MAC_DND BAT_NUM RGB_TEST` },
  { file: 'air60_v2_ansi', match: 'Air60 V2', roles: C7,
    custom: `${BASE} MAC_DND MAC_PRT MAC_PRTA SIDE_VAI SIDE_VAD SIDE_MOD SIDE_HUI SIDE_SPI SIDE_SPD DEV_RESET SLEEP_MODE BAT_SHOW RGB_TEST SHIFT_GRV BAT_NUM` },
  { file: 'air96_v2_ansi', match: 'Air96 V2', roles: C4,
    custom: `${BASE} MAC_DND MAC_PRT MAC_PRTA SIDE_VAI SIDE_VAD SIDE_MOD SIDE_HUI SIDE_SPI SIDE_SPD DEV_RESET SLEEP_MODE BAT_SHOW RGB_TEST BAT_NUM` },
  { file: 'halo75_v2_ansi', match: 'Halo75 V2', roles: C4,
    custom: `${BASE} MAC_DND MAC_PRT MAC_PRTA DEV_RESET SLEEP_MODE BAT_SHOW SIDE_VAI SIDE_VAD SIDE_MOD_A SIDE_MOD_B SIDE_HUI SIDE_SPI SIDE_SPD` },
  { file: 'halo65_v2_ansi', match: 'Halo65 V2', roles: C7,
    custom: `${BASE} MAC_DND MAC_PRT MAC_PRTA DEV_RESET SLEEP_MODE BAT_SHOW SIDE_VAI SIDE_VAD SIDE_MOD_A SIDE_MOD_B SIDE_HUI SIDE_SPI SIDE_SPD` },
  { file: 'halo96_v2_ansi', match: 'Halo96 V2', roles: C4,
    custom: `${BASE} MAC_DND MAC_PRT MAC_PRTA DEV_RESET SLEEP_MODE BAT_SHOW SIDE_VAI SIDE_VAD SIDE_MOD_A SIDE_MOD_B SIDE_HUI SIDE_SPI SIDE_SPD` },
];

const boards = MODELS.map(m => {
  const j = JSON.parse(fs.readFileSync(path.join(root, 'ref', m.file + '.json'), 'utf8'));
  const layout = Object.values(j.layouts)[0].layout;
  return {
    name: j.keyboard_name,
    vendorId: parseInt(j.usb.vid, 16),
    match: m.match,
    pids: m.pids || [parseInt(j.usb.pid, 16)],
    rows: j.matrix_pins.rows.length,
    cols: j.matrix_pins.cols.length,
    roles: m.roles,
    lighting: 'qmk_rgb_matrix',
    custom: m.custom.split(' '),
    keys: layout.map(k => [k.matrix[0], k.matrix[1], k.x, k.y, k.w || 1, k.h || 1]),
  };
});

const out = `// Generated by tools/gen-boards.js from nuphy-src/qmk_firmware (branch nuphy-keyboards). Do not edit by hand.
// keys: [row, col, x, y, w, h]
window.BUILTIN_BOARDS = ${JSON.stringify(boards)};
`;
fs.writeFileSync(path.join(root, 'src', 'boards.js'), out);
console.log(boards.map(b => `${b.name}: ${b.keys.length} keys, ${b.rows}x${b.cols}`).join('\n'));
